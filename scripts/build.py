#!/usr/bin/env python3
"""Build packaged presets and Agent Skills folders from presets.json.

Usage:
  python3 scripts/build.py           write packaged/*.skills.md and agent-skills/*/SKILL.md
  python3 scripts/build.py --check   exit 1 if any generated file is missing or out of date

Each preset is the exact concatenation of its source files, so a preset
cannot drift from its sources. Standard library only.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPO_URL = "https://github.com/harinee/agent-oss-dependency-policy"
SKILL_PREFIX = "oss-deps-"
NOTICE = "<!-- Generated by scripts/build.py from presets.json. Do not edit; edit the sources and rebuild. -->"


def title_of(path):
    for line in (ROOT / path).read_text().splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    raise SystemExit(f"{path}: no H1 title")


def preset_body(preset):
    parts = [
        f"# {preset['title']}",
        "",
        NOTICE,
        "",
        f"> {preset['summary']}",
        "",
        "**Included, in order:**",
        "",
    ]
    parts += [f"- {title_of(src)} (`{src}`)" for src in preset["sources"]]
    for src in preset["sources"]:
        parts += ["", "---", "", (ROOT / src).read_text().rstrip("\n")]
    return "\n".join(parts) + "\n"


def skill_description(preset):
    text = (
        "Policy for selecting, pinning and installing open-source dependencies. "
        "Use whenever you add, update, install or recommend a package, GitHub Action, "
        "container image, MCP server, editor extension or agent skill, or edit a "
        "manifest, lockfile or CI workflow. " + preset["summary"]
    )
    if len(text) > 1024:
        raise SystemExit(f"{preset['name']}: skill description is {len(text)} characters (max 1024)")
    return text


def skill_body(preset):
    name = SKILL_PREFIX + preset["name"]
    front = [
        "---",
        f"name: {name}",
        f"description: {json.dumps(skill_description(preset))}",
        "license: MIT",
        "metadata:",
        f"  source: {REPO_URL}",
        f"  preset: {preset['name']}",
        "---",
        "",
    ]
    return name, "\n".join(front) + preset_body(preset)


def outputs():
    presets = json.loads((ROOT / "presets.json").read_text())["presets"]
    out = {}
    for preset in presets:
        for src in preset["sources"]:
            if not (ROOT / src).is_file():
                raise SystemExit(f"{preset['name']}: missing source {src}")
        out[f"packaged/{preset['name']}.skills.md"] = preset_body(preset)
        name, body = skill_body(preset)
        out[f"agent-skills/{name}/SKILL.md"] = body
    return out


def main():
    check = "--check" in sys.argv[1:]
    expected = outputs()
    problems = []
    for rel, body in expected.items():
        path = ROOT / rel
        if check:
            if not path.is_file():
                problems.append(f"missing: {rel}")
            elif path.read_text() != body:
                problems.append(f"out of date: {rel}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body)
    # Generated files that no longer have a preset behind them.
    stale = [p for p in (ROOT / "packaged").glob("*.skills.md") if f"packaged/{p.name}" not in expected]
    stale += [p for p in (ROOT / "agent-skills").glob("*/SKILL.md")
              if str(p.relative_to(ROOT)) not in expected]
    for p in stale:
        problems.append(f"no preset for: {p.relative_to(ROOT)}")
    if check:
        if problems:
            print("\n".join(problems))
            print("Run: python3 scripts/build.py")
            return 1
        print(f"build check: {len(expected)} generated files are up to date")
        return 0
    if problems:
        print("\n".join(problems))
        return 1
    print(f"wrote {len(expected)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
